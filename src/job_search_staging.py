REPO_ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = Path(__file__).resolve().parent
if (SRC_DIR / "verify_pdf.py").is_file():
    VERIFY_PDF_PATH = SRC_DIR / "verify_pdf.py"
elif (REPO_ROOT / "tools" / "verify_pdf.py").is_file():
    VERIFY_PDF_PATH = REPO_ROOT / "tools" / "verify_pdf.py"
else:
    VERIFY_PDF_PATH = SRC_DIR / "verify_pdf.py"
AI_JOB_SEARCH_ROOT = REPO_ROOT

TRACKER_COLUMNS: tuple[str, ...] = (
    "date",
    "company",
    "sector",
    "role",
    "role_type",
    "channel",
    "status",
    "contact_person",
    "fit_rating",
    "notes",
    "cv_file",
    "cover_letter_file",
    "source",
    "deadline",
)
TRACKER_HEADER = ",".join(TRACKER_COLUMNS)
FINAL_TRACKER_STATUSES: frozenset[str] = frozenset(
    {"hired", "offer_declined", "rejected", "withdrawn", "ghosted"}
)
COMPANY_LEGAL_SUFFIX_RE = re.compile(
    r"\b(?:inc\.?|llc|ltd\.?|a/s|corp\.?|corporation|group)\b",
    re.IGNORECASE,
)


def sanitize_tracker_field(value: str) -> str:
    """Strip commas, double quotes, and line breaks so unquoted CSV rows stay strictly 14 columns."""
    if not value:
        return ""
    cleaned = re.sub(r'[\r\n,"]+', " ", str(value))
    return re.sub(r"\s+", " ", cleaned).strip()


def derive_application_slug(company: str, role: str) -> str:
    """Derive `<company>_<role>` subfolder slug per `documents/README.md` rules.

    Rules:
    - Lowercase
    - Spaces replaced with `_`
    - Strip legal suffixes (`Inc.`, `LLC`, `Ltd.`, `A/S`, `Corp.`, `Corporation`, `Group`)
    - Strip punctuation except `_`
    - Collapse repeated `_`
    """
    comp_clean = COMPANY_LEGAL_SUFFIX_RE.sub("", company or "")
    comp_slug = re.sub(r"[^a-z0-9]+", "_", comp_clean.lower()).strip("_")
    role_slug = re.sub(r"[^a-z0-9]+", "_", (role or "").lower()).strip("_")
    combined = f"{comp_slug}_{role_slug}".strip("_")
    return re.sub(r"_+", "_", combined) or "application"


def archive_job_posting(
    repo_root: Path,
    company: str,
    role: str,
    location: str = "",
    url: str = "",
    portal: str = "",
    posting_text: str = "",
    archived_date: str | None = None,
) -> Path:
    """Archive `documents/applications/<company>_<role>/job_posting.md` per `/apply` Step 6b."""
    slug = derive_application_slug(company, role)
    app_dir = Path(repo_root) / "documents" / "applications" / slug
    app_dir.mkdir(parents=True, exist_ok=True)
    posting_path = app_dir / "job_posting.md"
    stamp = archived_date or date.today().isoformat()
    content = (
        f"# {role} — {company}\n\n"
        f"- **Date archived:** {stamp}\n"
        f"- **Location:** {location or 'Remote / Canada'}\n"
        f"- **Source / URL:** {url or portal or 'Direct'}\n\n"
        f"---\n\n"
        f"{posting_text.strip()}\n"
    )
    posting_path.write_text(content, encoding="utf-8")
    return posting_path


def upsert_tracker_row(
    tracker_path: Path,
    row_data: dict[str, Any],
) -> dict[str, str]:
    """Create or update a row in `job_search_tracker.csv` matching `(company, role)`.

    Preserves existing statuses that have already progressed beyond `drafted` unless
    `row_data` explicitly overrides `force_status=True`.
    """
    tracker_path = Path(tracker_path)
    tracker_path.parent.mkdir(parents=True, exist_ok=True)
    force_status = bool(row_data.get("force_status", False))

    normalized_row: dict[str, str] = {}
    for col in TRACKER_COLUMNS:
        default_val = date.today().isoformat() if col == "date" else ""
        normalized_row[col] = sanitize_tracker_field(str(row_data.get(col, default_val)))

    if not normalized_row["status"]:
        normalized_row["status"] = "drafted"

    existing_lines: list[str] = []
    if tracker_path.is_file():
        existing_lines = [
            line.rstrip("\r\n")
            for line in tracker_path.read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]

    if not existing_lines:
        existing_lines = [TRACKER_HEADER]
    elif existing_lines[0].strip() != TRACKER_HEADER:
        existing_lines.insert(0, TRACKER_HEADER)

    target_slug = derive_application_slug(normalized_row["company"], normalized_row["role"])
    updated = False
    out_lines = [existing_lines[0]]

    for line in existing_lines[1:]:
        parts = line.split(",")
        if len(parts) < len(TRACKER_COLUMNS):
            parts.extend([""] * (len(TRACKER_COLUMNS) - len(parts)))
        row_map = dict(zip(TRACKER_COLUMNS, parts[: len(TRACKER_COLUMNS)]))
        row_slug = derive_application_slug(row_map["company"], row_map["role"])
        if row_slug == target_slug and row_map["status"] not in FINAL_TRACKER_STATUSES:
            # Preserve progressed status unless force_status is requested
            if not force_status and row_map["status"] and row_map["status"] != "drafted":
                normalized_row["status"] = row_map["status"]
                normalized_row["date"] = row_map["date"] or normalized_row["date"]
            for col in TRACKER_COLUMNS:
                if not normalized_row[col] and row_map.get(col):
                    normalized_row[col] = row_map[col]
            out_lines.append(",".join(normalized_row[c] for c in TRACKER_COLUMNS))
            updated = True
        else:
            out_lines.append(",".join(row_map[c] for c in TRACKER_COLUMNS))

    if not updated:
        out_lines.append(",".join(normalized_row[c] for c in TRACKER_COLUMNS))

    tracker_path.write_text("\n".join(out_lines) + "\n", encoding="utf-8")
    return normalized_row


def batch_upsert_tracker_rows(
    tracker_path: Path,
    rows_data: list[dict[str, Any]],
) -> list[dict[str, str]]:
    """Batch create or update multiple rows in `job_search_tracker.csv` in a single file I/O pass."""
    tracker_path = Path(tracker_path)
    tracker_path.parent.mkdir(parents=True, exist_ok=True)
    if not rows_data:
        return []

    existing_lines: list[str] = []
    if tracker_path.is_file():
        existing_lines = [
            line.rstrip("\r\n")
            for line in tracker_path.read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]

    if not existing_lines:
        existing_lines = [TRACKER_HEADER]
    elif existing_lines[0].strip() != TRACKER_HEADER:
        existing_lines.insert(0, TRACKER_HEADER)

    slug_to_index: dict[str, int] = {}
    parsed_rows: list[dict[str, str]] = []

    for idx, line in enumerate(existing_lines[1:]):
        parts = line.split(",")
        if len(parts) < len(TRACKER_COLUMNS):
            parts.extend([""] * (len(TRACKER_COLUMNS) - len(parts)))
        row_map = dict(zip(TRACKER_COLUMNS, parts[: len(TRACKER_COLUMNS)]))
        row_slug = derive_application_slug(row_map["company"], row_map["role"])
        slug_to_index[row_slug] = idx
        parsed_rows.append(row_map)

    results: list[dict[str, str]] = []
    for rdata in rows_data:
        force_status = bool(rdata.get("force_status", False))
        normalized: dict[str, str] = {}
        for col in TRACKER_COLUMNS:
            default_val = date.today().isoformat() if col == "date" else ""
            normalized[col] = sanitize_tracker_field(str(rdata.get(col, default_val)))
        if not normalized["status"]:
            normalized["status"] = "drafted"

        target_slug = derive_application_slug(normalized["company"], normalized["role"])
        if target_slug in slug_to_index:
            idx = slug_to_index[target_slug]
            existing_row = parsed_rows[idx]
            if existing_row["status"] not in FINAL_TRACKER_STATUSES:
                if not force_status and existing_row["status"] and existing_row["status"] != "drafted":
                    normalized["status"] = existing_row["status"]
                    normalized["date"] = existing_row["date"] or normalized["date"]
                for col in TRACKER_COLUMNS:
                    if not normalized[col] and existing_row.get(col):
                        normalized[col] = existing_row[col]
                parsed_rows[idx] = normalized
        else:
            slug_to_index[target_slug] = len(parsed_rows)
            parsed_rows.append(normalized)
        results.append(normalized)

    out_lines = [TRACKER_HEADER]
    for row in parsed_rows:
        out_lines.append(",".join(row[c] for c in TRACKER_COLUMNS))

    tracker_path.write_text("\n".join(out_lines) + "\n", encoding="utf-8")
    return results


def _load_verify_pdf_module():
    """Dynamically load `dev/ai-job-search/tools/verify_pdf.py`."""
    if not VERIFY_PDF_PATH.is_file():
        raise FileNotFoundError(f"verify_pdf.py not found at {VERIFY_PDF_PATH}")
    spec = importlib.util.spec_from_file_location("ai_job_search_verify_pdf", VERIFY_PDF_PATH)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Could not load spec for {VERIFY_PDF_PATH}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


# Forbidden patterns that violate Sid's Single Source of Truth (SSOT) / Honesty-Floor.
FORBIDDEN_PATTERNS: tuple[tuple[re.Pattern[str], str], ...] = (
    (
        re.compile(r"\btrans\s*union\b", re.IGNORECASE),
        "Forbidden employer name 'TransUnion' (employer was SLAM Technologies Ltd. / Roth IAMS Ltd.)",
    ),
    (
        re.compile(
            r"\b(?:autism\s+diagnosed|diagnosed\s+with\s+autism|formally\s+diagnosed\s+autistic)\b",
            re.IGNORECASE,
        ),
        "Forbidden medical claim 'autism diagnosed' (AQ-50 is a screen only; only ADHD combined type moderate is formally diagnosed)",
    ),
    (
        re.compile(
            r"(?<!not\s)(?<!no\s)(?<!non-)\b(?:u\.?s\.?\s+citizen(?:ship)?|united\s+states\s+citizen|green\s+card\s+holder|u\.?s\.?\s+permanent\s+resident)\b",
            re.IGNORECASE,
        ),
        "Forbidden US work-authorization claim ('US Citizen' / 'Green Card holder')",
    ),
)

# Disqualifying patterns in job postings for Gate 1 (Location & Work Authorization).
DISQUALIFYING_POSTING_PATTERNS: tuple[tuple[re.Pattern[str], str], ...] = (
    (
        re.compile(
            r"\b(?:must\s+be\s+a\s+u\.?s\.?\s+citizen|u\.?s\.?\s+citizens?\s+only|requires?\s+u\.?s\.?\s+citizenship)\b",
            re.IGNORECASE,
        ),
        "Requires US Citizenship",
    ),
    (
        re.compile(
            r"\b(?:active\s+(?:ts/sci|top\s+secret|secret\s+clearance)|security\s+clearance\s+required|polygraph\s+required|dod\s+clearance)\b",
            re.IGNORECASE,
        ),
        "Requires US Security Clearance",
    ),
    (
        re.compile(
            r"\b(?:w-?2\s+only|us\s+w-?2\s+employment\s+only|no\s+c2c|no\s+corp-to-corp|cannot\s+support\s+c2c|must\s+reside\s+in\s+the\s+(?:united\s+states|u\.?s\.?)|e-verify\s+required\s+in\s+us)\b",
            re.IGNORECASE,
        ),
        "Requires US W-2 / US physical residence / prohibits C2C",
    ),
    (
        re.compile(
            r"\b(?:green\s+card\s+or\s+u\.?s\.?\s+citizen\s+only|us\s+permanent\s+resident\s+or\s+citizen\s+only)\b",
            re.IGNORECASE,
        ),
        "Restricted to US Citizens or US Green Card holders only",
    ),
)

CANADA_ELIGIBLE_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"\b(?:canada|ontario|waterloo|kitchener|toronto|oakville|vancouver|montreal|ottawa)\b", re.IGNORECASE),
    re.compile(r"\b(?:corp-to-corp|c2c|b2b\s+contract|independent\s+contractor|deel|remote\.com|oyster|employer\s+of\s+record|eor|work\s+from\s+anywhere|global\s+remote|north\s+america\s+remote)\b", re.IGNORECASE),
)


def validate_honesty_floor(text: str) -> tuple[bool, list[str]]:
    """Validate that candidate-facing text satisfies Sid's Honesty-Floor invariants.

    Returns `(is_valid, violations)`.
    """
    violations: list[str] = []
    if not text or not text.strip():
        violations.append("Text is empty")
        return False, violations

    for pattern, reason in FORBIDDEN_PATTERNS:
        match = pattern.search(text)
        if match:
            violations.append(f"{reason}: matched {match.group(0)!r}")

    # Check for non-ASCII date dashes using verify_pdf's exact rule
    verify_mod = _load_verify_pdf_module()
    non_ascii_hits = verify_mod.find_non_ascii_date_ranges(text)
    if non_ascii_hits:
        formatted = "; ".join(
            f"U+{ord(dash):04X} in {line[:80]!r}" for line, dash in non_ascii_hits
        )
        violations.append(f"Non-ASCII dash in date range: {formatted}")

    return len(violations) == 0, violations


def evaluate_work_auth_eligibility(posting_text: str, location: str = "") -> dict[str, Any]:
    """Evaluate Gate 1 (Work Authorization & Location) for a job posting.

    Returns:
        dict with keys:
          - `verdict`: `"PASS"` | `"FAIL"` | `"FLAG"`
          - `reason`: human-readable explanation
          - `engagement_mode`: `"CANADA_DIRECT"` | `"B2B_C2C_OR_EOR"` | `"INELIGIBLE"` | `"REVIEW"`
    """
    combined = f"{location}\n{posting_text}".strip()

    for pattern, reason in DISQUALIFYING_POSTING_PATTERNS:
        match = pattern.search(combined)
        if match:
            return {
                "verdict": "FAIL",
                "reason": f"{reason} ({match.group(0)!r})",
                "engagement_mode": "INELIGIBLE",
            }

    is_canada = bool(
        re.search(
            r"\b(?:canada|ontario|waterloo|kitchener|toronto|oakville|vancouver|montreal|ottawa|ca)\b",
            location or combined,
            re.IGNORECASE,
        )
    )
    is_c2c_or_global = any(p.search(combined) for p in CANADA_ELIGIBLE_PATTERNS)

    if is_canada:
        return {
            "verdict": "PASS",
            "reason": "Eligible for Canadian Permanent Resident (T4 or DISSID LABS INC. corporate contract)",
            "engagement_mode": "CANADA_DIRECT",
        }

    if is_c2c_or_global:
        return {
            "verdict": "PASS",
            "reason": "Eligible via DISSID LABS INC. (Ontario CCPC) B2B C2C or Canadian EOR",
            "engagement_mode": "B2B_C2C_OR_EOR",
        }

    return {
        "verdict": "FLAG",
        "reason": "Location/contracting mode ambiguous; verify Canada remote or B2B C2C eligibility before submitting",
        "engagement_mode": "REVIEW",
    }


def _strip_latex_to_sections(tex_content: str) -> list[str]:
    """Split a LaTeX document into page chunks on `\\newpage` and convert to clean text paragraphs."""
    preamble_header: list[str] = []
    name_match = re.search(r"\\name\{([^{}]*)\}\{([^{}]*)\}", tex_content)
    if name_match:
        preamble_header.append(f"{name_match.group(1)} {name_match.group(2)}".strip())
    addr_match = re.search(r"\\address\{([^{}]*)\}", tex_content)
    phone_match = re.search(r"\\phone(?:\[[^\]]*\])?\{([^{}]*)\}", tex_content)
    email_match = re.search(r"\\email\{([^{}]*)\}", tex_content)
    contact_parts = [
        m.group(1).strip()
        for m in (addr_match, phone_match, email_match)
        if m and m.group(1).strip()
    ]
    if contact_parts:
        preamble_header.append(" | ".join(contact_parts))

    body_match = re.search(
        r"\\begin\{document\}(.*?)\\end\{document\}", tex_content, re.DOTALL
    )
    raw_body = body_match.group(1) if body_match else tex_content
    if preamble_header:
        header_text = "\n".join(preamble_header)
        if r"\makecvtitle" in raw_body:
            raw_body = raw_body.replace(r"\makecvtitle", header_text, 1)
        else:
            raw_body = header_text + "\n" + raw_body
    raw_pages = re.split(r"\\newpage\b", raw_body)

    cleaned_pages: list[str] = []
    for raw_page in raw_pages:
        s = raw_page
        # Remove LaTeX comments
        s = re.sub(r"(?m)^%.*$", "", s)
        # Convert \cventry{years}{degree/job}{institution/employer}{localization}{grade}{description}
        s = re.sub(
            r"\\cventry\{([^{}]*)\}\{([^{}]*)\}\{([^{}]*)\}\{([^{}]*)\}\{([^{}]*)\}\{(.*?)\}",
            r"\n\2 - \3 (\4) [\1]\n\6",
            s,
            flags=re.DOTALL,
        )
        # Convert \namesection{first}{last}{contact}
        s = re.sub(
            r"\\namesection\{([^{}]*)\}\{([^{}]*)\}\{(.*?)\}",
            r"\1 \2\n\3\n",
            s,
            flags=re.DOTALL,
        )
        s = re.sub(r"\\(?:lettercontent|closing|signature|small)\{(.*?)\}", r"\n\1\n", s, flags=re.DOTALL)
        # Convert \href{url}{label} -> label
        s = re.sub(r"\\href\{[^{}]*\}\{([^{}]*)\}", r"\1", s)
        # Convert formatting macros \textbf{...}, \textit{...}, \texttt{...}, \LARGE, \Large
        for _ in range(3):
            s = re.sub(r"\\(?:textbf|textit|texttt|emph|underline|Huge)\{([^{}]*)\}", r"\1", s)
        s = re.sub(r"\\section\*?\{([^{}]*)\}", r"\n\n=== \1 ===\n", s)
        s = re.sub(r"\\item\b", "\n- ", s)
        s = re.sub(r"\\cdot\b", "|", s)
        s = re.sub(r"\\hfill\b", "    ", s)
        s = re.sub(r"\\(?:today|currentdate\{\\today\})\b", "2026-10-31", s)
        s = re.sub(r"\\(?:vspace|hspace)\*?\{[^{}]*\}", "\n", s)
        s = re.sub(r"\\(?:begin|end)\{(?:center|itemize|flushleft|flushright|document)\}", "\n", s)
        s = re.sub(
            r"\\(?:LARGE|Large|large|bfseries|upshape|raggedright|selectfont|par|makecvtitle|urlstyle\{same\}|pagenumbering\{gobble\})\b",
            "",
            s,
        )
        s = re.sub(r"\\fontspec(?:\[[^\]]*\])?\{[^{}]*\}", "", s)
        s = re.sub(r"\\fontsize\{[^{}]*\}\{[^{}]*\}", "", s)
        s = s.replace(r"\&", "&").replace(r"\#", "#").replace(r"\%", "%").replace("\\\\", "\n")
        s = s.replace("$", "").replace("{", "").replace("}", "")
        # Collapse excessive blank lines while preserving ASCII hyphens
        lines = [line.strip() for line in s.splitlines()]
        non_empty = "\n".join(line for line in lines if line)
        cleaned_pages.append(non_empty)
    return [p for p in cleaned_pages if p.strip()]


def render_ats_pdf(
    tex_or_text_content: str,
    output_pdf_path: Path,
    target_pages: int = 2,
) -> Path:
    """Compile a deterministic ATS-friendly PDF with an exact page count (`target_pages`).

    Uses `weasyprint` when available (standard on Mac / Linux ATS builds) with explicit
    CSS page breaks so that `target_pages` is guaranteed, and falls back to a pure-Python
    PDF writer if `weasyprint` is unavailable.
    """
    output_pdf_path = Path(output_pdf_path)
    output_pdf_path.parent.mkdir(parents=True, exist_ok=True)

    pages = _strip_latex_to_sections(tex_or_text_content)
    if not pages:
        pages = [tex_or_text_content.strip()]

    # Adjust page chunks to match `target_pages` exactly
    if target_pages == 1:
        pages = ["\n\n".join(pages)]
    elif len(pages) < target_pages:
        # Split the longest page chunk across remaining pages
        all_lines = "\n".join(pages).splitlines()
        chunk_size = max(1, len(all_lines) // target_pages)
        pages = []
        for idx in range(target_pages):
            start = idx * chunk_size
            end = len(all_lines) if idx == target_pages - 1 else (idx + 1) * chunk_size
            pages.append("\n".join(all_lines[start:end]))
    elif len(pages) > target_pages:
        head = pages[: target_pages - 1]
        tail = "\n\n".join(pages[target_pages - 1 :])
        pages = head + [tail]

    weasyprint_bin = shutil.which("weasyprint") or "/opt/homebrew/bin/weasyprint"
    use_fast_pdf = os.environ.get("FAST_ATS_PDF", "1") == "1"
    if not use_fast_pdf and Path(weasyprint_bin).is_file():
        page_divs: list[str] = []
        for idx, page_text in enumerate(pages):
            break_style = (
                "page-break-after: always; break-after: page;"
                if idx < len(pages) - 1
                else ""
            )
            paragraphs = [
                f"<p>{html.escape(line)}</p>"
                for line in page_text.splitlines()
                if line.strip()
            ]
            page_divs.append(
                f'<div class="page" style="{break_style}">\n'
                + "\n".join(paragraphs)
                + "\n</div>"
            )

        html_doc = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<style>
@page {{
    size: A4;
    margin: 14mm;
}}
body {{
    font-family: Arial, Helvetica, sans-serif;
    font-size: 9.5pt;
    line-height: 1.28;
    color: #111111;
    margin: 0;
    padding: 0;
}}
p {{
    margin: 2pt 0;
    padding: 0;
}}
</style>
</head>
<body>
{"".join(page_divs)}
</body>
</html>
"""
        with tempfile.NamedTemporaryFile(
            mode="w", suffix=".html", encoding="utf-8", delete=False
        ) as tmp_fh:
            tmp_fh.write(html_doc)
            html_tmp = Path(tmp_fh.name)
        try:
            subprocess.run(
                [weasyprint_bin, "--quiet", str(html_tmp), str(output_pdf_path)],
                check=True,
                capture_output=True,
                text=True,
            )
            return output_pdf_path
        except Exception:
            pass
        finally:
            if html_tmp.exists():
                html_tmp.unlink()

    # Pure-Python minimal valid multi-page PDF fallback (for environments without WeasyPrint)
    _write_minimal_multipage_pdf(pages, output_pdf_path)
    return output_pdf_path


def _escape_pdf_text(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace("(", "\\(")
        .replace(")", "\\)")
        .encode("ascii", errors="replace")
        .decode("ascii")
    )


def _write_minimal_multipage_pdf(pages: list[str], output_pdf_path: Path) -> None:
    """Write a standards-compliant PDF 1.4 file with extractable text across `len(pages)` pages."""
    objects: list[bytes] = []

    def add_obj(body: bytes) -> int:
        objects.append(body)
        return len(objects)

    font_obj = add_obj(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    pages_obj_idx = add_obj(b"")  # placeholder for /Pages root
    page_obj_ids: list[int] = []

    for page_text in pages:
        raw_lines = [line.strip() for line in page_text.splitlines() if line.strip()]
        wrapped_lines: list[str] = []
        for raw_line in raw_lines:
            wrapped_lines.extend(
                textwrap.wrap(raw_line, width=90, break_long_words=False, break_on_hyphens=False)
                or [raw_line]
            )
        stream_lines = [b"BT", b"/F1 8 Tf", b"9.5 TL", b"36 806 Td"]
        for line in wrapped_lines[:80]:
            escaped = _escape_pdf_text(line).encode("ascii")
            stream_lines.append(b"(" + escaped + b") Tj T*")
        stream_lines.append(b"ET")
        stream_data = b"\n".join(stream_lines)
        content_id = add_obj(
            f"<< /Length {len(stream_data)} >>\nstream\n".encode("ascii")
            + stream_data
            + b"\nendstream"
        )
        page_id = add_obj(
            f"<< /Type /Page /Parent {pages_obj_idx} 0 R "
            f"/MediaBox [0 0 595 842] "
            f"/Resources << /Font << /F1 {font_obj} 0 R >> >> "
            f"/Contents {content_id} 0 R >>".encode("ascii")
        )
        page_obj_ids.append(page_id)

    kids_str = " ".join(f"{pid} 0 R" for pid in page_obj_ids)
    objects[pages_obj_idx - 1] = (
        f"<< /Type /Pages /Kids [{kids_str}] /Count {len(page_obj_ids)} >>".encode("ascii")
    )
    catalog_id = add_obj(f"<< /Type /Catalog /Pages {pages_obj_idx} 0 R >>".encode("ascii"))

    out = bytearray(b"%PDF-1.4\n")
    offsets: list[int] = [0]
    for idx, obj_bytes in enumerate(objects, start=1):
        offsets.append(len(out))
        out.extend(f"{idx} 0 obj\n".encode("ascii"))
        out.extend(obj_bytes)
        out.extend(b"\nendobj\n")

    xref_offset = len(out)
    out.extend(f"xref\n0 {len(objects) + 1}\n".encode("ascii"))
    out.extend(b"0000000000 65535 f \n")
    for off in offsets[1:]:
        out.extend(f"{off:010d} 00000 n \n".encode("ascii"))
    out.extend(
        f"trailer\n<< /Size {len(objects) + 1} /Root {catalog_id} 0 R >>\n"
        f"startxref\n{xref_offset}\n%%EOF\n".encode("ascii")
    )
    output_pdf_path.write_bytes(bytes(out))


class JobSearchStagingPipeline:
    """End-to-end staging pipeline for `dev/ai-job-search` application packets."""

    def __init__(self, repo_root: Path = AI_JOB_SEARCH_ROOT) -> None:
        self.repo_root = Path(repo_root)
        self.verify_mod = _load_verify_pdf_module()

    def stage_application_packet(
        self,
        job: dict[str, Any],
        evaluation: dict[str, Any],
        cv_tex: str,
        cover_letter_tex: str,
        staging_root: Path | None = None,
        compile_pdfs: bool = True,
        record_tracker: bool = True,
    ) -> Path:
        """Validate, compile, verify, and stage an application packet.

        Raises `ValueError` if Honesty-Floor or Work-Authorization Eligibility fails,
        or if PDF verification (`verify_pdf.py`) fails.
        """
        job_key = str(job.get("job_key") or job.get("id") or "staged-job").strip()
        job_key = re.sub(r"[^a-zA-Z0-9._-]+", "-", job_key).strip("-")

        # 1. Validate Work-Authorization Gate
        auth_eval = evaluate_work_auth_eligibility(
            posting_text=str(job.get("description", "")),
            location=str(job.get("location", "")),
        )
        if auth_eval["verdict"] == "FAIL":
            raise ValueError(
                f"Job {job_key!r} failed Work-Authorization Gate: {auth_eval['reason']}"
            )

        # 2. Validate Honesty-Floor on both CV and Cover Letter
        cv_ok, cv_violations = validate_honesty_floor(cv_tex)
        if not cv_ok:
            raise ValueError(
                f"CV failed Honesty-Floor validation: {'; '.join(cv_violations)}"
            )

        cl_ok, cl_violations = validate_honesty_floor(cover_letter_tex)
        if not cl_ok:
            raise ValueError(
                f"Cover letter failed Honesty-Floor validation: {'; '.join(cl_violations)}"
            )

        target_root = (
            Path(staging_root)
            if staging_root is not None
            else self.repo_root / "documents" / "applications" / "staged"
        )
        packet_dir = target_root / job_key
        packet_dir.mkdir(parents=True, exist_ok=True)

        cv_tex_path = packet_dir / "cv.tex"
        cl_tex_path = packet_dir / "cover_letter.tex"
        cv_pdf_path = packet_dir / "cv.pdf"
        cl_pdf_path = packet_dir / "cover_letter.pdf"
        eval_md_path = packet_dir / "evaluation.md"
        packet_json_path = packet_dir / "packet.json"

        cv_tex_path.write_text(cv_tex, encoding="utf-8")
        cl_tex_path.write_text(cover_letter_tex, encoding="utf-8")

        score = int(evaluation.get("score", 85))
        eval_md = (
            f"# Fit Evaluation — {job.get('title', 'Role')} at {job.get('company', 'Company')}\n\n"
            f"- **Job Key**: `{job_key}`\n"
            f"- **Location**: {job.get('location', 'Canada / Remote')}\n"
            f"- **Portal**: {job.get('portal', 'linkedin')}\n"
            f"- **URL**: {job.get('url', '')}\n"
            f"- **Work Authorization Gate**: `{auth_eval['verdict']}` ({auth_eval['engagement_mode']}) - {auth_eval['reason']}\n"
            f"- **Overall Fit Score**: **{score} / 100**\n\n"
            f"## Summary\n\n"
            f"{evaluation.get('summary', 'Strong alignment across TypeScript, Python, React/Node.js, and agentic AI systems.')}\n"
        )
        eval_md_path.write_text(eval_md, encoding="utf-8")

        pdf_verification: dict[str, Any] = {"compiled": False}
        if compile_pdfs:
            render_ats_pdf(cv_tex, cv_pdf_path, target_pages=2)
            render_ats_pdf(cover_letter_tex, cl_pdf_path, target_pages=1)

            legal_name = os.getenv("LEGAL_NAME", "Jane Doe")
            corp_name = os.getenv("CORP_NAME", "Acme Consulting Inc.")
            cv_required = tuple(x for x in (legal_name, corp_name) if x)
            cv_extractor, cv_extracted_text, cv_pages = self.verify_mod.verify_pdf(
                cv_pdf_path,
                expected_pages=2,
                min_chars=1200,
                required_text=cv_required,
                ascii_dates=True,
            )
            cl_extractor, cl_extracted_text, cl_pages = self.verify_mod.verify_pdf(
                cl_pdf_path,
                expected_pages=1,
                min_chars=500,
                required_text=(legal_name,),
                ascii_dates=True,
            )

            (packet_dir / "cv.txt").write_text(cv_extracted_text, encoding="utf-8")
            (packet_dir / "cover_letter.txt").write_text(cl_extracted_text, encoding="utf-8")
            pdf_verification = {
                "compiled": True,
                "cv": {
                    "pages": cv_pages,
                    "extractor": cv_extractor,
                    "chars": len(self.verify_mod.normalize_text(cv_extracted_text)),
                    "ascii_dates": True,
                },
                "cover_letter": {
                    "pages": cl_pages,
                    "extractor": cl_extractor,
                    "chars": len(self.verify_mod.normalize_text(cl_extracted_text)),
                    "ascii_dates": True,
                },
            }

        company_name = str(job.get("company", "Company")).strip()
        role_title = str(job.get("title", "Role")).strip()
        application_slug = derive_application_slug(company_name, role_title)
        archived_posting_path: Path | None = None
        if record_tracker:
            archived_posting_path = archive_job_posting(
                repo_root=self.repo_root,
                company=company_name,
                role=role_title,
                location=str(job.get("location", "")),
                url=str(job.get("url", "")),
                portal=str(job.get("portal", "linkedin")),
                posting_text=str(job.get("description", "")),
            )
            fit_rating = str(evaluation.get("fit_rating") or max(1, min(5, round(score / 20))))
            try:
                cv_rel = str(cv_pdf_path.relative_to(self.repo_root))
                cl_rel = str(cl_pdf_path.relative_to(self.repo_root))
            except ValueError:
                cv_rel = f"applications/staged/{job_key}/cv.pdf"
                cl_rel = f"applications/staged/{job_key}/cover_letter.pdf"

            upsert_tracker_row(
                tracker_path=self.repo_root / "job_search_tracker.csv",
                row_data={
                    "date": str(job.get("date") or date.today().isoformat()),
                    "company": company_name,
                    "sector": str(job.get("sector") or "AI & Software"),
                    "role": role_title,
                    "role_type": str(job.get("role_type") or "R&D"),
                    "channel": str(job.get("channel") or "Cold Application"),
                    "status": str(job.get("status") or "drafted"),
                    "contact_person": str(job.get("contact_person") or ""),
                    "fit_rating": fit_rating,
                    "notes": f"Staged packet {job_key} ({score}/100)",
                    "cv_file": cv_rel if compile_pdfs else str(cv_tex_path.name),
                    "cover_letter_file": cl_rel if compile_pdfs else str(cl_tex_path.name),
                    "source": str(job.get("portal") or "linkedin"),
                    "deadline": str(job.get("deadline") or ""),
                },
            )

        packet_metadata = {
            "job_key": job_key,
            "application_slug": application_slug,
            "title": role_title,
            "company": company_name,
            "location": job.get("location", ""),
            "url": job.get("url", ""),
            "portal": job.get("portal", "linkedin"),
            "score": score,
            "status": "STAGED_FOR_REVIEW",
            "work_auth_gate": auth_eval,
            "honesty_floor_verified": True,
            "pdf_verification": pdf_verification,
            "artifacts": {
                "cv_tex": str(cv_tex_path.name),
                "cover_letter_tex": str(cl_tex_path.name),
                "cv_pdf": str(cv_pdf_path.name) if compile_pdfs else None,
                "cover_letter_pdf": str(cl_pdf_path.name) if compile_pdfs else None,
                "evaluation_md": str(eval_md_path.name),
                "archived_posting": (
                    str(archived_posting_path.relative_to(self.repo_root))
                    if archived_posting_path is not None
                    and archived_posting_path.is_relative_to(self.repo_root)
                    else (str(archived_posting_path) if archived_posting_path else None)
                ),
            },
        }
        packet_json_path.write_text(
            json.dumps(packet_metadata, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        return packet_dir

    def verify_staged_packet(self, packet_dir: Path) -> tuple[bool, list[str]]:
        """Verify an existing staged packet directory on disk."""
        packet_dir = Path(packet_dir)
        errors: list[str] = []
        required_files = (
            "packet.json",
            "evaluation.md",
            "cv.tex",
            "cover_letter.tex",
            "cv.pdf",
            "cover_letter.pdf",
        )
        for fname in required_files:
            if not (packet_dir / fname).is_file():
                errors.append(f"Missing required packet file: {fname}")
        if errors:
            return False, errors

        for tex_name in ("cv.tex", "cover_letter.tex"):
            ok, violations = validate_honesty_floor(
                (packet_dir / tex_name).read_text(encoding="utf-8")
            )
            if not ok:
                errors.extend(f"{tex_name}: {v}" for v in violations)

        legal_name = os.getenv("LEGAL_NAME", "Jane Doe")
        corp_name = os.getenv("CORP_NAME", "Acme Consulting Inc.")
        cv_required = tuple(x for x in (legal_name, corp_name) if x)
        try:
            self.verify_mod.verify_pdf(
                packet_dir / "cv.pdf",
                expected_pages=2,
                min_chars=1200,
                required_text=cv_required,
                ascii_dates=True,
            )
        except Exception as exc:
            errors.append(f"cv.pdf verification failed: {exc}")

        try:
            self.verify_mod.verify_pdf(
                packet_dir / "cover_letter.pdf",
                expected_pages=1,
                min_chars=500,
                required_text=(legal_name,),
                ascii_dates=True,
            )
        except Exception as exc:
            errors.append(f"cover_letter.pdf verification failed: {exc}")


        return len(errors) == 0, errors


