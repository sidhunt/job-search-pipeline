#!/usr/bin/env python3
"""JobSearchStagingPipeline — Honesty-Floor, Work-Auth Gate & Staged-Packet Builder.

Provides deterministic validation, PDF compilation, and staging for job application
packets generated by local LLM inference or edge workers.

Key invariants:
1. Honesty-Floor (`validate_honesty_floor`):
   - Rejects forbidden employer hallucinations (`TransUnion`), unverified medical claims
     (`autism diagnosed`, `diagnosed with autism`), and false citizenship claims
     (`US Citizen`, `U.S. Citizen`, `Green Card holder`, `Canadian Citizen` before oath).
   - Enforces ASCII date ranges (no en-dash/em-dash joined to 4-digit years).
2. Work-Authorization Eligibility Gate (`evaluate_work_auth_eligibility`):
   - PASS: Canada remote/hybrid/onsite (T4 or contract) OR US/Global remote roles
     eligible for Canada / B2B Corp-to-Corp (`DISSID LABS INC.`) / EOR.
   - FAIL: US W-2-only requiring US physical presence, US Citizenship, US Permanent
     Residency (Green Card), E-Verify, or US Security Clearance (TS/SCI, Secret, Polygraph).
3. Staged-Packet Verification (`stage_application_packet`, `verify_staged_packet`):
   - Writes `packet.json`, `evaluation.md`, `cv.tex`, `cover_letter.tex`, and compiles
     verified ATS PDFs (`cv.pdf` = 2 pages, `cover_letter.pdf` = 1 page) validated by
     `dev/ai-job-search/tools/verify_pdf.py --ascii-dates`.
"""

